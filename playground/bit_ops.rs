// ============================================================
// 비트 연산 플레이그라운드
// SHA-256을 이해하기 위한 기초 연습장
// ============================================================

// 이진수 문자열("1010")을 넣으면 정수(10)로 바꿔주는 함수
// "1010" → 10
// "1100" → 12
// "11111111" → 255
fn bin_to_int(binary_str: &str) -> u32 {
    // u32::from_str_radix(문자열, 진법)
    // 2진법(radix=2)으로 된 문자열을 숫자로 변환한다.
    // JavaScript로 치면: parseInt("1010", 2) → 10
    u32::from_str_radix(binary_str, 2).expect("올바른 이진수를 입력하세요")
}

// 정수를 이진수 문자열로 바꿔주는 함수 (8자리로 맞춤)
// 10 → "00001010"
// 12 → "00001100"
fn int_to_bin(num: u32) -> String {
    // {:08b} → 8자리 이진수로 표시, 빈자리는 0으로 채움
    format!("{:08b}", num)
}

fn main() {
    println!("╔══════════════════════════════════════════════╗");
    println!("║   비트 연산 플레이그라운드                    ║");
    println!("╚══════════════════════════════════════════════╝\n");

    // ============================================================
    // 1. 이진수 ↔ 정수 변환 연습
    // ============================================================
    println!("=== 1. 이진수 ↔ 정수 변환 ===\n");

    let a_bin = "1010";
    let b_bin = "1100";

    let a = bin_to_int(a_bin);  // 10
    let b = bin_to_int(b_bin);  // 12

    println!("  a = {} (이진수) = {} (정수)", a_bin, a);
    println!("  b = {} (이진수) = {} (정수)", b_bin, b);

    // ============================================================
    // 2. XOR 연산 — 다르면 1, 같으면 0
    // ============================================================
    println!("\n=== 2. XOR 연산 (다르면 1, 같으면 0) ===\n");

    // Rust에서 XOR 연산자는 ^ 이다.
    let xor_result = a ^ b;

    println!("  a     = {}", int_to_bin(a));
    println!("  b     = {}", int_to_bin(b));
    println!("         --------");
    println!("  a ^ b = {}  (정수: {})", int_to_bin(xor_result), xor_result);
    println!();
    println!("  자리별 확인:");
    println!("    1 vs 1 → 같다  → 0");
    println!("    0 vs 1 → 다르다 → 1");
    println!("    1 vs 0 → 다르다 → 1");
    println!("    0 vs 0 → 같다  → 0");

    // ============================================================
    // 3. AND 연산 — 둘 다 1이면 1
    // ============================================================
    println!("\n=== 3. AND 연산 (둘 다 1이면 1) ===\n");

    // Rust에서 AND 연산자는 & 이다.
    let and_result = a & b;

    println!("  a     = {}", int_to_bin(a));
    println!("  b     = {}", int_to_bin(b));
    println!("         --------");
    println!("  a & b = {}  (정수: {})", int_to_bin(and_result), and_result);
    println!();
    println!("  자리별 확인:");
    println!("    1 AND 1 → 둘 다 1 → 1");
    println!("    0 AND 1 → 하나가 0 → 0");
    println!("    1 AND 0 → 하나가 0 → 0");
    println!("    0 AND 0 → 둘 다 0 → 0");

    // ============================================================
    // 4. NOT 연산 — 뒤집기 (0→1, 1→0)
    // ============================================================
    println!("\n=== 4. NOT 연산 (뒤집기) ===\n");

    // Rust에서 NOT 연산자는 ! 이다.
    // u8로 캐스팅해서 8비트만 보여준다 (32비트 전부 뒤집으면 너무 길어서)
    let a_u8 = a as u8;
    let not_result = !a_u8;

    println!("  a  = {:08b}  (정수: {})", a_u8, a_u8);
    println!("  !a = {:08b}  (정수: {})", not_result, not_result);
    println!();
    println!("  모든 비트가 뒤집힌다: 0→1, 1→0");

    // ============================================================
    // 5. 비트 시프트 — 밀기
    // ============================================================
    println!("\n=== 5. 비트 시프트 (밀기) ===\n");

    // >> 오른쪽으로 밀기, << 왼쪽으로 밀기
    // 밀면 빈자리는 0으로 채워진다.
    let shift_right = a_u8 >> 2;  // 오른쪽으로 2칸
    let shift_left = a_u8 << 2;   // 왼쪽으로 2칸

    println!("  a      = {:08b}  (정수: {})", a_u8, a_u8);
    println!("  a >> 2 = {:08b}  (정수: {})  ← 오른쪽으로 2칸 밀기", shift_right, shift_right);
    println!("  a << 2 = {:08b}  (정수: {})  ← 왼쪽으로 2칸 밀기", shift_left, shift_left);

    // ============================================================
    // 6. 이것들을 조합하면? (SHA-256이 하는 짓)
    // ============================================================
    println!("\n=== 6. 조합 — SHA-256이 하는 짓의 축소판 ===\n");

    let x: u8 = bin_to_int("11001010") as u8;
    let y: u8 = bin_to_int("10110011") as u8;

    println!("  입력:");
    println!("    x = {:08b}", x);
    println!("    y = {:08b}", y);

    // 1단계: x를 오른쪽으로 3칸 밀기
    let step1 = x >> 3;
    println!("\n  1단계: x >> 3     = {:08b}", step1);

    // 2단계: 1단계 결과와 y를 XOR
    let step2 = step1 ^ y;
    println!("  2단계: step1 ^ y  = {:08b}", step2);

    // 3단계: 2단계 결과와 x를 AND
    let step3 = step2 & x;
    println!("  3단계: step2 & x  = {:08b}", step3);

    // 4단계: 덧셈 (넘치면 잘라냄 — wrapping_add)
    let step4 = step3.wrapping_add(y);
    println!("  4단계: step3 + y  = {:08b}", step4);

    println!("\n  최종 결과: {:08b} (정수: {})", step4, step4);
    println!("  원래 입력: x={:08b}, y={:08b}", x, y);
    println!("\n  → 결과만 보고 x, y를 알아낼 수 있을까? 불가능!");
    println!("  → 이걸 64번 반복하면? 그게 SHA-256이다!");
}
